def krawtchouk_table():
    table = []
    for frequency_weight in range(8):
        coefficients = [1]
        for coordinate in range(7):
            next_coefficients = [0]*(len(coefficients)+1)
            multiplier = -1 if coordinate < frequency_weight else 2
            for degree, value in enumerate(coefficients):
                next_coefficients[degree] += value
                next_coefficients[degree+1] += multiplier*value
            coefficients = next_coefficients
        table.append(coefficients)
    return np.array(table, dtype=np.int64)


def collapsed_codes(canonical, points):
    pairs = list(combinations(range(4), 2))
    duplicate_mask = np.zeros(len(points), dtype=np.int64)
    for i, (a,b) in enumerate(pairs):
        duplicate_mask += np.all(points[:,a,:] == points[:,b,:], axis=1)*(1<<i)
    answer = np.empty(len(points), dtype=np.int64)
    for mask in np.unique(duplicate_mask):
        selected = np.flatnonzero(duplicate_mask == mask)
        representatives = []
        for i in range(4):
            if not any(mask & (1<<pairs.index((j,i))) for j in representatives):
                representatives.append(i)
        answer[selected] = canonical.codes(points[selected][:,representatives,:])
    return answer



def rebuild(codes):
    canonical=Canonical()
    words=np.array(list(product(range(3),repeat=7)),dtype=np.int64)
    V=len(codes);lookup={int(code):i for i,code in enumerate(codes)}
    patterns = np.array(canonical.patterns[4], dtype=np.int64)
    pairs = list(combinations(range(4), 2))
    def pattern_id(symbols):
        equality = sum(1<<i for i,(a,b) in enumerate(pairs) if symbols[a] == symbols[b])
        return int(canonical.lookup[4][equality])
    equal_choices = Counter(pattern_id((0,0,w,z)) for w,z in product(range(3),repeat=2))
    different_choices = Counter(pattern_id((0,1,w,z)) for w,z in product(range(3),repeat=2))
    assert sum(equal_choices.values()) == sum(different_choices.values()) == 9
    powers = [8**i for i in range(14)]
    krawtchouk = krawtchouk_table()  # table[k,d] = K_d(k).
    shell = np.array([comb(7,i)*2**i for i in range(8)], dtype=np.int64)
    # The dual identity also checks which Krawtchouk index is the frequency.
    assert np.array_equal(shell[:,None]*krawtchouk, shell[None,:]*krawtchouk.T)
    rebuilt = np.zeros((8,64,V+1), dtype=np.int64)
    records = []
    for d in range(8):
        polynomial = {0:1}
        for coordinate in range(7):
            choices = different_choices if coordinate < d else equal_choices
            next_polynomial = Counter()
            for key, coefficient in polynomial.items():
                for pattern, multiplicity in choices.items():
                    next_polynomial[key+powers[pattern]] += coefficient*multiplicity
            polynomial = next_polynomial
        assert sum(polynomial.values()) == 2187**2
        histograms = np.array([[(key//power)%8 for power in powers] for key in polynomial], dtype=np.int64)
        points = np.array([np.repeat(patterns, row, axis=0).T for row in histograms])
        orbit_codes = collapsed_codes(canonical, points)
        i_values = np.count_nonzero(points[:,0,:] != points[:,2,:], axis=1)
        j_values = np.count_nonzero(points[:,1,:] != points[:,3,:], axis=1)
        totals = np.zeros((8,8), dtype=np.int64)
        for coefficient, code, i, j in zip(polynomial.values(), orbit_codes, i_values, j_values):
            totals[i,j] += coefficient
            for k in range(8):
                rebuilt[k,8*i+j,lookup[int(code)]] += coefficient*int(krawtchouk[k,d])
        assert np.array_equal(totals, shell[:,None]*shell[None,:])
        records.append({"anchor_distance":d,"histograms":len(polynomial),
                        "ordered_pairs_counted":sum(polynomial.values()),
                        "every_shell_pair_total_correct":True})
        print("Fourier anchored count pass",d,len(polynomial),flush=True)
    assert sum(row["histograms"] for row in records) == 77520
    for k in range(8):
        assert np.array_equal(rebuilt[k].reshape(8,8,V+1),rebuilt[k].reshape(8,8,V+1).transpose(1,0,2))
    print("all eight coefficient matrices match exactly",flush=True)

    return rebuilt
